type I18nContextValue = {
  readonly locale: AppLocale;
  readonly setLocale: (locale: AppLocale) => void;
  readonly t: (key: TranslationKey, values?: Readonly<Record<string, string | number>>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function translate(locale: AppLocale, key: TranslationKey, values?: Readonly<Record<string, string | number>>): string {
  const template = locale === "ja-JP" ? ja[key] : zh[key];
  return Object.entries(values ?? {}).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template);
}

export function I18nProvider({ children }: { readonly children: ReactNode }) {
  const [locale, setLocale] = useState<AppLocale>(DEFAULT_APP_LOCALE);

  useEffect(() => {
    let cancelled = false;
    const api = window.api ?? window.novelTool;
    if (!api) return;
    void api.settings.get().then((settings) => {
      if (!cancelled) setLocale((settings as SettingsState).appLocale ?? DEFAULT_APP_LOCALE);
    }).catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => translate(locale, key, values)
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is missing.");
  return value;
}
